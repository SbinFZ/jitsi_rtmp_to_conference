func TestSourceNameAndSanitize(t *testing.T) {
	id := ParticipantIdentity{
		Endpoint:    "422ab3db",
		DisplayName: "Alice Smith",
		VideoType:   "camera",
	}
	got := SourceName("Jitsi", "team-sync", id)
	want := "Jitsi (team-sync) - Alice Smith [422ab3db]"
	if got != want {
		t.Fatalf("SourceName = %q, want %q", got, want)
	}

	idScreen := ParticipantIdentity{
		Endpoint:    "422ab3db",
		DisplayName: "Alice Smith",
		VideoType:   "desktop",
	}
	gotScreen := SourceName("", "team-sync", idScreen)
	wantScreen := "Jitsi (team-sync) - Alice Smith [422ab3db] (Screen)"
	if gotScreen != wantScreen {
		t.Fatalf("SourceName screen = %q, want %q", gotScreen, wantScreen)
	}

	if tok := SanitizeToken("Alice Smith / 2026!"); tok != "Alice_Smith_2026" {
		t.Fatalf("SanitizeToken = %q, want Alice_Smith_2026", tok)
	}
}

func TestBuildSDPAndFFmpegArgs(t *testing.T) {
	sdp := BuildSDP("Jitsi (room) - Bob [1234]", 5004, 5006)
	if !strings.Contains(sdp, "m=audio 5004 RTP/AVP 111") || !strings.Contains(sdp, "a=rtpmap:111 opus/48000/2") {
		t.Fatalf("missing audio SDP lines:\n%s", sdp)
	}
	if !strings.Contains(sdp, "m=video 5006 RTP/AVP 96") || !strings.Contains(sdp, "a=rtpmap:96 VP8/90000") {
		t.Fatalf("missing video SDP lines:\n%s", sdp)
	}

	args := BuildFFmpegArgs("/tmp/test.sdp", "libndi_newtek", "Jitsi (room) - Bob [1234]")
	joined := strings.Join(args, " ")
	if !strings.Contains(joined, "-f libndi_newtek Jitsi (room) - Bob [1234]") || !strings.Contains(joined, "-pix_fmt uyvy422") {
		t.Fatalf("unexpected NDI ffmpeg args: %v", args)
	}
}

func TestBroadcasterWithSinkCommand(t *testing.T) {
	tmp := t.TempDir()
	marker := filepath.Join(tmp, "env.txt")

	sinkCmd := "echo $JITSI_NDI_NAME/$JITSI_ENDPOINT > env.txt"
	if runtime.GOOS == "windows" {
		sinkCmd = "echo %JITSI_NDI_NAME%/%JITSI_ENDPOINT%>env.txt"
	}

	b := NewBroadcaster(Config{
		Enabled: true,
		Room:    "testroom",
		Prefix:  "Jitsi",
		OutDir:  tmp,
		SinkCmd: sinkCmd,
	})
	defer func() {
		_ = b.Close()
	}()

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	pkt := &rtp.Packet{
		Header: rtp.Header{
			Version:        2,
			PayloadType:    111,
			SequenceNumber: 1,
			Timestamp:      480,
			SSRC:           998877,
		},
		Payload: []byte{0x01, 0x02, 0x03, 0x04},
	}

	id := ParticipantIdentity{
		Endpoint:    "ep01",
		DisplayName: "Charlie",
		VideoType:   "camera",
	}

	if err := b.WriteRTP(ctx, id, 998877, false, pkt); err != nil {
		t.Fatalf("WriteRTP failed: %v", err)
	}

	sources := b.ActiveSources()
	if len(sources) != 1 || sources[0] != "Jitsi (testroom) - Charlie [ep01]" {
		t.Fatalf("unexpected active sources: %v", sources)
	}

	deadline := time.Now().Add(5 * time.Second)
	for time.Now().Before(deadline) {
		data, err := os.ReadFile(marker)
		if err == nil && strings.Contains(string(data), "\n") {
			got := strings.TrimSpace(string(data))
			if got != "Jitsi (testroom) - Charlie [ep01]/ep01" {
				t.Fatalf("unexpected sink env marker: %q", got)
			}
			_ = b.Close()
			return
		}
		time.Sleep(25 * time.Millisecond)
	}
	_ = b.Close()
	t.Fatalf("timed out waiting for sink command to write marker file")
}

func TestBroadcasterRealFFmpegMultiParticipantWebM(t *testing.T) {
	ffmpegPath, err := exec.LookPath("ffmpeg")
	if err != nil {
		if _, statErr := os.Stat("/opt/homebrew/bin/ffmpeg"); statErr == nil {
			ffmpegPath = "/opt/homebrew/bin/ffmpeg"
		} else {
			t.Skip("ffmpeg not installed")
		}
	}
	ffprobePath, _ := exec.LookPath("ffprobe")
	if ffprobePath == "" {
		if _, statErr := os.Stat("/opt/homebrew/bin/ffprobe"); statErr == nil {
			ffprobePath = "/opt/homebrew/bin/ffprobe"
		}
	}

	tmp := t.TempDir()
	b := NewBroadcaster(Config{
		Enabled:   true,
		Room:      "live-demo",
		Prefix:    "Jitsi",
		Format:    "webm",
		FFmpegBin: ffmpegPath,
		OutDir:    tmp,
	})
	defer func() {
		_ = b.Close()
	}()

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	// Create two local UDP sockets to capture real VP8 + Opus RTP packets generated by FFmpeg
	vConn, err := net.ListenUDP("udp4", &net.UDPAddr{IP: net.IPv4(127, 0, 0, 1), Port: 0})
	if err != nil {
		t.Fatalf("ListenUDP video: %v", err)
	}
	defer vConn.Close()
	vPort := vConn.LocalAddr().(*net.UDPAddr).Port

	aConn, err := net.ListenUDP("udp4", &net.UDPAddr{IP: net.IPv4(127, 0, 0, 1), Port: 0})
	if err != nil {
		t.Fatalf("ListenUDP audio: %v", err)
	}
	defer aConn.Close()
	aPort := aConn.LocalAddr().(*net.UDPAddr).Port

	alice := ParticipantIdentity{
		Endpoint:    "ep-alice",
		DisplayName: "Alice",
		VideoType:   "camera",
	}
	bobScreen := ParticipantIdentity{
		Endpoint:    "ep-bob",
		DisplayName: "Bob",
		VideoType:   "desktop",
	}

	// Pre-warm both audio and video tracks for Alice and Bob so FFmpeg binds SDP ports before the main RTP burst
	warmupV := &rtp.Packet{
		Header:  rtp.Header{Version: 2, PayloadType: 96, SequenceNumber: 1, Timestamp: 0, SSRC: 1001},
		Payload: []byte{0x10, 0x02, 0x00, 0x9d, 0x01, 0x2a, 0x40, 0x01, 0xf0, 0x00},
	}
	warmupA := &rtp.Packet{
		Header:  rtp.Header{Version: 2, PayloadType: 111, SequenceNumber: 1, Timestamp: 0, SSRC: 1002},
		Payload: []byte{0xf8, 0xff, 0xfe},
	}
	_ = b.WriteRTP(ctx, alice, 1002, false, warmupA)
	_ = b.WriteRTP(ctx, alice, 1001, true, warmupV)
	_ = b.WriteRTP(ctx, bobScreen, 2002, false, warmupA)
	_ = b.WriteRTP(ctx, bobScreen, 2001, true, warmupV)
	time.Sleep(250 * time.Millisecond)

	// Pump RTP packets into Broadcaster for both Alice and Bob
	donePump := make(chan struct{})
	go func() {
		defer close(donePump)
		buf := make([]byte, 2048)
		for {
			_ = vConn.SetReadDeadline(time.Now().Add(200 * time.Millisecond))
			n, _, err := vConn.ReadFromUDP(buf)
			if err != nil {
				if ctx.Err() != nil {
					return
				}
				continue
			}
			var pkt rtp.Packet
			if err := pkt.Unmarshal(buf[:n]); err == nil {
				_ = b.WriteRTP(ctx, alice, 1001, true, &pkt)
				_ = b.WriteRTP(ctx, bobScreen, 2001, true, &pkt)
			}
		}
	}()

	go func() {
		buf := make([]byte, 2048)
		for {
			_ = aConn.SetReadDeadline(time.Now().Add(200 * time.Millisecond))
			n, _, err := aConn.ReadFromUDP(buf)
			if err != nil {
				if ctx.Err() != nil {
					return
				}
				continue
			}
			var pkt rtp.Packet
			if err := pkt.Unmarshal(buf[:n]); err == nil {
				_ = b.WriteRTP(ctx, alice, 1002, false, &pkt)
				_ = b.WriteRTP(ctx, bobScreen, 2002, false, &pkt)
			}
		}
	}()

	// Run FFmpeg generator to produce 2.0 seconds of real VP8 RTP + Opus RTP
	genCmd := exec.CommandContext(ctx, ffmpegPath,
		"-hide_banner", "-loglevel", "error",
		"-re",
		"-f", "lavfi", "-i", "testsrc=size=320x240:rate=15:duration=2.0",
		"-f", "lavfi", "-i", "sine=frequency=440:sample_rate=48000:duration=2.0",
		"-map", "0:v:0", "-an", "-c:v", "libvpx", "-b:v", "200k", "-g", "5", "-payload_type", "96", "-f", "rtp", "rtp://127.0.0.1:"+itoa(vPort),
		"-map", "1:a:0", "-vn", "-c:a", "libopus", "-b:a", "48k", "-payload_type", "111", "-f", "rtp", "rtp://127.0.0.1:"+itoa(aPort),
	)
	if out, err := genCmd.CombinedOutput(); err != nil {
		t.Fatalf("ffmpeg RTP generator failed: %v (%s)", err, string(out))
	}

	// Give FFmpeg consumer processes a moment to flush received packets, then close broadcaster cleanly
	time.Sleep(400 * time.Millisecond)
	cancel()
	<-donePump
	if err := b.Close(); err != nil {
		t.Fatalf("Broadcaster.Close: %v", err)
	}

	aliceWebM := filepath.Join(tmp, "participant-ep-alice.webm")
	bobWebM := filepath.Join(tmp, "participant-ep-bob-desktop.webm")

	for _, f := range []string{aliceWebM, bobWebM} {
		st, err := os.Stat(f)
		if err != nil {
			t.Fatalf("expected output file %s missing: %v", f, err)
		}
		if st.Size() < 1024 {
			t.Fatalf("expected non-trivial media file %s, got %d bytes", f, st.Size())
		}
		t.Logf("Verified real demuxed participant output: %s (%d bytes)", filepath.Base(f), st.Size())

		if ffprobePath != "" {
			probeOut, err := exec.Command(ffprobePath,
				"-v", "error",
				"-show_entries", "stream=codec_type,codec_name,width,height,sample_rate",
				"-of", "json",
				f,
			).CombinedOutput()
			if err != nil {
				t.Fatalf("ffprobe failed on %s: %v (%s)", f, err, string(probeOut))
			}
			var parsed struct {
				Streams []struct {
					CodecType string `json:"codec_type"`
					CodecName string `json:"codec_name"`
				} `json:"streams"`
			}
			if err := json.Unmarshal(probeOut, &parsed); err != nil {
				t.Fatalf("unmarshal ffprobe json: %v", err)
			}
			if len(parsed.Streams) < 2 {
				t.Fatalf("expected both audio and video streams in %s, got: %s", f, string(probeOut))
			}
			t.Logf("ffprobe streams for %s: %s", filepath.Base(f), strings.TrimSpace(string(probeOut)))
		}
	}
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var buf [20]byte
	i := len(buf)
	for n > 0 {
		i--
		buf[i] = byte('0' + n%10)
		n /= 10
	}
	return string(buf[i:])
}
